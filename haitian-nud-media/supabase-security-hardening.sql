-- DADINIO security hardening migration
-- Apply ONCE to the existing Supabase/Postgres database after reviewing the current schema.
-- This migration does not rotate or modify any API keys or .env values.

BEGIN;

-- The admin predicate runs with the function owner's privileges to avoid recursive RLS checks.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.users
    WHERE id = auth.uid()
      AND is_admin IS TRUE
      AND COALESCE(blocked, FALSE) IS FALSE
  );
$$;

REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_admin() TO anon, authenticated;

-- Private event ledger for authenticated photo views. Browser roles receive
-- no table privileges; only the SECURITY DEFINER counter function can write it.
CREATE TABLE IF NOT EXISTS public.photo_view_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  photo_id UUID NOT NULL REFERENCES public.photos(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS photo_view_events_lookup_idx
ON public.photo_view_events (photo_id, user_id, created_at DESC);

ALTER TABLE public.photo_view_events ENABLE ROW LEVEL SECURITY;

-- The admin dashboard uses this aggregate. Restrict it to active administrators
-- and pin the SECURITY DEFINER function to a safe search_path.
CREATE OR REPLACE FUNCTION public.get_total_views()
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $total_views$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'ADMIN_REQUIRED'
      USING ERRCODE = '42501';
  END IF;

  RETURN
    COALESCE((SELECT SUM(views) FROM public.videos), 0)
    + COALESCE((SELECT SUM(views) FROM public.photos), 0);
END;
$total_views$;

REVOKE ALL ON FUNCTION public.get_total_views() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_total_views() TO authenticated;

-- Harden the existing audit trigger function. The audit table and its
-- columns are already used by the live audit triggers.
CREATE OR REPLACE FUNCTION public.audit_trigger_fn()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $audit$
BEGIN
  INSERT INTO public.audit_log (table_name, operation, user_id, old_data, new_data)
  VALUES (
    TG_TABLE_NAME,
    TG_OP,
    auth.uid(),
    CASE WHEN TG_OP = 'DELETE' THEN row_to_json(OLD)::jsonb ELSE NULL END,
    CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN row_to_json(NEW)::jsonb ELSE NULL END
  );
  RETURN COALESCE(NEW, OLD);
END;
$audit$;

REVOKE ALL ON FUNCTION public.audit_trigger_fn() FROM PUBLIC, anon, authenticated;

-- Preserve the one-view-per-hour rule for authenticated visitors while
-- pinning the SECURITY DEFINER function to a safe search_path.
CREATE OR REPLACE FUNCTION public.can_insert_view(p_video_id UUID)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $can_view$
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN TRUE;
  END IF;

  RETURN NOT EXISTS (
    SELECT 1
    FROM public.views
    WHERE video_id = p_video_id
      AND user_id = auth.uid()
      AND created_at > NOW() - INTERVAL '1 hour'
  );
END;
$can_view$;

REVOKE ALL ON FUNCTION public.can_insert_view(UUID) FROM PUBLIC, anon, authenticated;

