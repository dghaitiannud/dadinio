-- RLS does not govern TRUNCATE, REFERENCES, TRIGGER, or MAINTAIN privileges.
-- Remove every direct table grant from PUBLIC/anon/authenticated, then grant
-- only the object privileges exercised by the frontend. service_role is kept
-- untouched for trusted backend operations.
DO $acl$
DECLARE
  table_name TEXT;
  column_name TEXT;
  table_oid REGCLASS;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'videos', 'photos', 'comments', 'downloads', 'views',
    'photo_view_events', 'tickets', 'push_subscriptions', 'audit_log',
    'vip_requests', 'video_ads', 'live_status', 'app_settings', 'app_banner'
  ] LOOP
    table_oid := to_regclass(format('public.%I', table_name));
    IF table_oid IS NOT NULL THEN
      -- Table-level grants include TRUNCATE/REFERENCES/TRIGGER/MAINTAIN,
      -- none of which are required by the browser roles.
      EXECUTE format(
        'REVOKE ALL PRIVILEGES ON TABLE public.%I FROM PUBLIC, anon, authenticated',
        table_name
      );

      -- Column ACLs are independent of table ACLs; remove any old column grants too.
      FOR column_name IN
        SELECT a.attname
        FROM pg_attribute a
        WHERE a.attrelid = table_oid
          AND a.attnum > 0
          AND NOT a.attisdropped
          AND a.attacl IS NOT NULL
      LOOP
        EXECUTE format(
          'REVOKE ALL PRIVILEGES (%I) ON TABLE public.%I FROM PUBLIC, anon, authenticated',
          column_name,
          table_name
        );
      END LOOP;
    END IF;
  END LOOP;
END;
$acl$;

