-- Keep the existing public view-counter RPC compatible with the frontend,
-- while fixing its SECURITY DEFINER search_path and qualifying the target table.
CREATE OR REPLACE FUNCTION public.increment_video_views(video_id UUID)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $views$
DECLARE
  v_user_id UUID := auth.uid();
  v_is_vip BOOLEAN;
  v_published BOOLEAN;
  v_blocked BOOLEAN;
  v_is_admin BOOLEAN;
  v_plan TEXT;
  v_subscription_ends_at TIMESTAMPTZ;
  v_has_vip BOOLEAN;
BEGIN
  -- Anonymous requests cannot mutate counters: the public anon key is not
  -- an identity and cannot provide a meaningful per-view rate limit.
  IF v_user_id IS NULL THEN
    RETURN;
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('video:' || video_id::text || ':' || v_user_id::text, 0)
  );

  SELECT
    v.is_vip,
    v.published,
    COALESCE(u.blocked, FALSE),
    COALESCE(u.is_admin, FALSE),
    u.plan,
    u.subscription_ends_at
  INTO
    v_is_vip,
    v_published,
    v_blocked,
    v_is_admin,
    v_plan,
    v_subscription_ends_at
  FROM public.videos v
  JOIN public.users u ON u.id = v_user_id
  WHERE v.id = increment_video_views.video_id;

  IF NOT FOUND OR v_published IS NOT TRUE OR v_blocked THEN
    RETURN;
  END IF;

  v_has_vip := COALESCE(v_is_admin, FALSE) OR COALESCE(
    v_plan = 'vip'
    AND (v_subscription_ends_at IS NULL OR v_subscription_ends_at > now()),
    FALSE
  );

  IF v_is_vip IS TRUE AND NOT v_has_vip THEN
    RETURN;
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.views v_event
    WHERE v_event.video_id = increment_video_views.video_id
      AND v_event.user_id = v_user_id
      AND v_event.created_at > now() - INTERVAL '1 hour'
  ) THEN
    RETURN;
  END IF;

  INSERT INTO public.views (video_id, user_id)
  VALUES (increment_video_views.video_id, v_user_id);

  UPDATE public.videos v
  SET views = COALESCE(v.views, 0) + 1
  WHERE v.id = increment_video_views.video_id;
END;
$views$;

REVOKE ALL ON FUNCTION public.increment_video_views(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.increment_video_views(UUID) TO authenticated;

