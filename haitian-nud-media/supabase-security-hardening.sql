-- Administrator status is preserved as already configured in the existing users table.
-- This migration deliberately does not elevate accounts by matching an email address.

-- Ordinary users may update display_name and confirm their age, but never their role,
-- plan, block state, quota, subscription dates, email, or identity.
CREATE OR REPLACE FUNCTION public.guard_user_privileged_fields()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  -- Only administrators and the trusted backend service may modify protected
  -- account fields. SECURITY DEFINER ownership is not used as a bypass because
  -- unrelated definer functions may share the same owner.
  IF current_user = 'service_role' OR public.is_admin() THEN
    RETURN NEW;
  END IF;

  -- A user may only increase their own free-download counter by one. This
  -- cannot unlock downloads or reduce the quota; the trusted RPC remains the
  -- only way to obtain a download URL.
  IF NEW.free_downloads_used IS DISTINCT FROM OLD.free_downloads_used
     AND NEW.free_downloads_used IS DISTINCT FROM COALESCE(OLD.free_downloads_used, 0) + 1 THEN
    RAISE EXCEPTION 'USER_PRIVILEGED_FIELDS_PROTECTED'
      USING ERRCODE = '42501';
  END IF;

  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.email IS DISTINCT FROM OLD.email
     OR NEW.plan IS DISTINCT FROM OLD.plan
     OR NEW.is_admin IS DISTINCT FROM OLD.is_admin
     OR NEW.role IS DISTINCT FROM OLD.role
     OR NEW.blocked IS DISTINCT FROM OLD.blocked
     OR NEW.subscription_ends_at IS DISTINCT FROM OLD.subscription_ends_at
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'USER_PRIVILEGED_FIELDS_PROTECTED'
      USING ERRCODE = '42501';
  END IF;

  IF OLD.age_confirmed IS TRUE AND NEW.age_confirmed IS DISTINCT FROM OLD.age_confirmed THEN
    RAISE EXCEPTION 'AGE_CONFIRMATION_CANNOT_BE_REVERSED'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$;

-- This function is invoked only by the trigger on public.users.
REVOKE ALL ON FUNCTION public.guard_user_privileged_fields() FROM PUBLIC, anon, authenticated;

